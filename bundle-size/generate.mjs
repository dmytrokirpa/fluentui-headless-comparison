import { writeFile, readdir, unlink, copyFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { libraries, components, resolveImports } from './manifest.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');

const renderFixture = (name, imports) => {
  const lines = imports.map((imp, i) =>
    imp.named
      ? `import { ${imp.named} as M${i} } from '${imp.from}';`
      : `import * as M${i} from '${imp.from}';`,
  );
  const refs = imports.map((_, i) => `M${i}`).join(', ');
  return [
    '// generated by bundle-size/generate.mjs — do not edit',
    ...lines,
    '',
    `console.log({ ${refs} });`,
    '',
    'export default {',
    `  name: '${name}',`,
    '};',
    '',
  ].join('\n');
};

const clean = async () => {
  const files = await readdir(here);
  await Promise.all(
    files
      .filter((f) => f.endsWith('.fixture.js'))
      .map((f) => unlink(path.join(here, f))),
  );
};

const generate = async () => {
  let written = 0;
  for (const libKey of Object.keys(libraries)) {
    const aggregate = [];
    for (const Component of Object.keys(components)) {
      const imports = resolveImports(libKey, Component);
      if (!imports) continue;
      const name = `${libKey}/${Component}`;
      await writeFile(
        path.join(here, `${libKey}${Component}.fixture.js`),
        renderFixture(name, imports),
      );
      aggregate.push(...imports);
      written++;
    }
    if (aggregate.length > 0) {
      await writeFile(
        path.join(here, `${libKey}All.fixture.js`),
        renderFixture(`${libKey}/All`, aggregate),
      );
      written++;
    }
  }
  return written;
};

const copyReport = async () => {
  const src = path.join(repoRoot, 'dist/bundle-size/monosize.json');
  if (!existsSync(src)) return false;
  const destDir = path.join(repoRoot, 'public');
  await mkdir(destDir, { recursive: true });
  await copyFile(src, path.join(destDir, 'monosize.json'));
  return true;
};

const mode = process.argv[2] ?? 'fixtures';

if (mode === 'fixtures') {
  await clean();
  const n = await generate();
  console.log(`Generated ${n} fixtures in bundle-size/`);
} else if (mode === 'copy-report') {
  const ok = await copyReport();
  console.log(
    ok
      ? 'Copied dist/bundle-size/monosize.json → public/monosize.json'
      : 'No monosize.json to copy (run `monosize measure` first)',
  );
} else {
  console.error(`Unknown mode: ${mode}. Use "fixtures" or "copy-report".`);
  process.exit(1);
}
